"""Build native/signatures.txt: for each function of interest find a wildcarded byte pattern that is unique in the
(unpacked) mc9.exe, plus a string anchor as a second way to find it. The DLL repeats the same search at run time,
so another MC9 build only needs `python tools/sigmaker.py <its unpacked exe>` - no hand-collected offsets.

usage: python tools/sigmaker.py mc9.exe [targets.txt] > native/signatures.txt
targets.txt lines:  name = "anchor string" [index]      (function that contains the index-th reference to the string)
                    name = 0x00401000                   (a known function start; the anchor stays empty)
"""

from __future__ import annotations

import re
import struct
import sys

import capstone
import pefile

MAX_LEN = 56


class Image:
    def __init__(self, path):
        self.pe = pefile.PE(path)
        self.base = self.pe.OPTIONAL_HEADER.ImageBase
        self.img = bytes(self.pe.get_memory_mapped_image())
        self.hi = len(self.img)
        self.md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
        self.md.detail = True

    def in_image(self, va):
        return self.base + 0x1000 <= va < self.base + self.hi

    def find_string(self, s):
        needle = s.encode() + b"\0"
        i = self.img.find(needle)
        while i >= 0:
            if i == 0 or self.img[i - 1] == 0:
                return self.base + i
            i = self.img.find(needle, i + 1)
        return None

    def code_ref(self, off):
        p1, p2 = self.img[off - 1], self.img[off - 2]
        if p1 == 0x68 or 0xB8 <= p1 <= 0xBF or p1 in (0xA1, 0xA3):
            return True
        if (p1 & 0xC7) == 0x05 and p2 in (0x8B, 0x8D, 0x89, 0x03, 0x3B, 0x39, 0x2B, 0xFF):
            return True
        return ((p1 & 0xF8) == 0xC0 and p2 == 0x81) or (p1 == 0x05 and p2 == 0xC7)

    def xrefs(self, va):
        v = struct.pack("<I", va)
        out, i = [], self.img.find(v, 0x1000)
        while i >= 0:
            if self.code_ref(i):
                out.append(i)
            i = self.img.find(v, i + 1)
        return out

    def func_start(self, off):
        for c in range(off, max(off - 0x4000, 0x1000), -1):
            if (self.img[c - 1] == 0xCC and self.img[c] != 0xCC and (self.base + c) % 16 == 0
                    and (self.img[c - 2] in (0xCC, 0xC3) or self.img[c - 4] == 0xC2)):
                return c
        return None

    def mask(self, off, n):
        """n bytes at off as (bytes, wildcard flags); absolute addresses and branch displacements are wildcards."""
        data = self.img[off:off + n + 16]
        wild = [False] * len(data)
        done = 0
        for ins in self.md.disasm(data, self.base + off):
            o = ins.address - (self.base + off)
            for fld_off, fld_size in ((ins.disp_offset, ins.disp_size), (ins.imm_offset, ins.imm_size)):
                if fld_size == 4:
                    val = struct.unpack_from("<I", data, o + fld_off)[0]
                    rel = ins.group(capstone.CS_GRP_JUMP) or ins.group(capstone.CS_GRP_CALL)
                    if rel or self.in_image(val):
                        for k in range(4):
                            wild[o + fld_off + k] = True
            done = o + ins.size
            if done >= n:
                break
        return data[:done], wild[:done]

    def count(self, pat):
        """Number of matches of a wildcard pattern in the image (regex over bytes)."""
        rx = b"".join(b"." if w else re.escape(bytes([b])) for b, w in pat)
        return len(re.findall(b"(?=" + rx + b")", self.img, flags=re.S))

    def signature(self, off):
        data, wild = self.mask(off, MAX_LEN)
        for n in range(8, len(data) + 1):
            pat = list(zip(data[:n], wild[:n]))
            if all(w for _, w in pat[-1:]):      # do not end on a wildcard: keep the pattern tight
                continue
            if self.count(pat) == 1:
                return " ".join("??" if w else "%02X" % b for b, w in pat)
        return None


def main():
    exe = sys.argv[1]
    targets = open(sys.argv[2]).read().splitlines() if len(sys.argv) > 2 else []
    im = Image(exe)
    print("# generated by tools/sigmaker.py - name | wildcard byte pattern | string anchor | which reference of the anchor | RVA in the build it was made from")
    for line in targets:
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        name, spec = [x.strip() for x in line.split("=", 1)]
        m = re.match(r'"(.*)"\s*(\d+)?$', spec)
        if m:
            anchor, which = m.group(1), int(m.group(2) or 0)
            s = im.find_string(anchor)
            refs = im.xrefs(s) if s else []
            if len(refs) <= which:
                print("# %s: anchor %r has %d reference(s)" % (name, anchor, len(refs)), file=sys.stderr)
                continue
            start = im.func_start(refs[which])
        else:
            anchor, which, start = "", 0, int(spec, 16) - im.base
        sig = im.signature(start) if start else None
        print("%s | %s | %s | %d | %x" % (name, sig or "", anchor, which, start))
        print("# %s -> %#x%s" % (name, im.base + start, "" if sig else "  (no unique pattern)"), file=sys.stderr)


if __name__ == "__main__":
    main()
